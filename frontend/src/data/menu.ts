/* ------------------------------ helpers ------------------------------ */

export const categoryById = (id: string): Category =>
  CATEGORIES.find((c) => c.id === id) ?? CATEGORIES[0];

export const itemsByCategory = (id: string): FoodItem[] =>
  MENU.filter((m) => m.category === id);

export const itemById = (id: string): FoodItem | undefined =>
  MENU.find((m) => m.id === id);

export const relatedItems = (item: FoodItem, count = 4): FoodItem[] => {
  const same = MENU.filter((m) => m.category === item.category && m.id !== item.id);
  const others = MENU.filter((m) => m.category !== item.category && m.tag);
  return [...same, ...others].slice(0, count);
};

export const signatureItems = (): FoodItem[] =>
  MENU.filter((m) => m.tag === "Bestseller" || m.tag === "Chef's Special").slice(0, 8);

export const formatPrice = (n: number) => `₹${n.toLocaleString("en-IN")}`;

